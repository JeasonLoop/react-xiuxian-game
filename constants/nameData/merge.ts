/**
 * 装备命名四档合并词库
 *
 * 数据来源（constants/nameData/ 下 JSON，原文件保持原样不修改）：
 * - talisman/talisman.json —— 器型词（7 档稀有度）
 * - talisman/material.json、material/material.json —— 器物材质词
 * - shared/color.json —— 颜色字（与材质字组合成普通档材质词）
 * - shared/spirit.json —— 灵性字（秘/精/真/宝/古/玄…）
 * - shared/common.json —— 通用双字词（道号/天象/灵兽/名物/数词/动作等）
 * - shared/strange.json —— 《山海经》式生僻双字名（传说名号用）
 * - creature/*.json —— 灵兽字（主要服务宠物命名，此处仅少量借用于灵韵词）
 * - alchemy/alchemy.json、talisman/postfix.json、material/postfix.json ——
 *   丹药器型与破损/赝品后缀，与装备命名语义不符，不参与合并
 *
 * 7 档 → 4 档映射：common/uncommon→普通、rare→稀有、epic/legendary→传说、mythic/exotic→仙品
 * 项目 tsconfig 未开启 resolveJsonModule，故按原始 JSON 手写为 TS 常量（词面一致）。
 *
 * 说明：talisman.json 的器型词多为法宝/通用器型，若直接按档位套用到护甲、戒指
 * 会产生「精铁眼睛」式违和组合，因此按器型类别（武器/护甲/饰品/戒指/法宝）
 * 重新归类分档，并与项目自有槽位词（armorParts、accessoryTypes、ringTypes 等）
 * 合并去重，原始分档信息保留在 TALISMAN_TYPE_BY_TIER 供追溯。
 */

/** 四档稀有度（与项目 ItemRarity 一致） */
